#!/usr/bin/env python3
"""Generate the development Ed25519 signing key, or export a public key as C.

  keygen.py [--out keys/dev_ed25519.pem] [--force]
      New keypair: the private key (PKCS#8 PEM, file mode 0600) and the
      public key next to it (<name>.pub.pem). Refuses to overwrite a key.

  keygen.py --export-c OUT.c --key KEY.pem
      Write the public key of KEY.pem (private or public PEM) as the C array
      g_bms_signing_pubkey that the bootloader and the application link.

DEVELOPMENT ONLY. The private key lives unencrypted on disk, and keys/ is in
.gitignore so it can never be committed. A production key would be generated
inside an HSM and never leave it: the build server sends image digests to a
signing service and gets signatures back, and only the public key is ever
exported - which is all the firmware build needs (--export-c accepts a
public key PEM for exactly that reason).
"""
from __future__ import annotations

import argparse
import os
import sys
from pathlib import Path

from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey, Ed25519PublicKey

sys.path.insert(0, str(Path(__file__).resolve().parent))
from bms_image import key_id  # noqa: E402


def load_public_key(path: Path) -> Ed25519PublicKey:
    data = path.read_bytes()
    try:
        key = serialization.load_pem_private_key(data, password=None)
    except ValueError:  # not a private key: try a public one
        key = serialization.load_pem_public_key(data)
    if isinstance(key, Ed25519PrivateKey):
        key = key.public_key()
    if not isinstance(key, Ed25519PublicKey):
        raise SystemExit(f"{path} is not an Ed25519 key")
    return key


def raw_public(key: Ed25519PublicKey) -> bytes:
    return key.public_bytes(serialization.Encoding.Raw, serialization.PublicFormat.Raw)


def generate(out: Path, force: bool) -> None:
    pub_path = out.with_suffix(".pub.pem")
    if out.exists() and not force:
        raise SystemExit(f"{out} already exists - refusing to overwrite a signing key (use --force)")
    out.parent.mkdir(parents=True, exist_ok=True)
    key = Ed25519PrivateKey.generate()
    pem = key.private_bytes(serialization.Encoding.PEM, serialization.PrivateFormat.PKCS8,
                            serialization.NoEncryption())
    # Create with 0600 from the start: no window where others could read it.
    fd = os.open(out, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "wb") as f:
        f.write(pem)
    pub_path.write_bytes(key.public_key().public_bytes(serialization.Encoding.PEM,
                                                       serialization.PublicFormat.SubjectPublicKeyInfo))
    print(f"generated development signing key {out} (key id {key_id(raw_public(key.public_key()))})")
    print("  images signed with any previous key will now be rejected by a newly built bootloader")


def export_c(key_path: Path, out: Path) -> None:
    raw = raw_public(load_public_key(key_path))
    body = ",\n".join("    " + ", ".join(f"0x{b:02x}" for b in raw[i:i + 8]) for i in range(0, len(raw), 8))
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(
        f"/* Generated by tools/keygen.py from {key_path.as_posix()} - do not edit.\n"
        f" * Ed25519 public key, key id {key_id(raw)}. Images must be signed with the\n"
        f" * matching private key to boot (bootloader) or to be accepted over CAN (app). */\n"
        "#include \"bms_keys.h\"\n\n"
        "const uint8_t g_bms_signing_pubkey[BMS_IMAGE_PUBKEY_SIZE] = {\n"
        f"{body},\n"
        "};\n\n"
        f"const char g_bms_signing_key_id[] = \"{key_id(raw)}\";\n")


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="Development Ed25519 signing key tool")
    ap.add_argument("--out", type=Path, default=Path("keys/dev_ed25519.pem"), help="private key to create")
    ap.add_argument("--force", action="store_true", help="overwrite an existing key")
    ap.add_argument("--export-c", type=Path, metavar="OUT.c", help="write the public key as C source")
    ap.add_argument("--key", type=Path, help="key to export (private or public PEM)")
    args = ap.parse_args(argv)

    if args.export_c:
        if args.key is None:
            ap.error("--export-c needs --key")
        export_c(args.key, args.export_c)
    else:
        generate(args.out, args.force)
    return 0


if __name__ == "__main__":
    sys.exit(main())
